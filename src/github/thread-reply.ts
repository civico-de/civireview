import type { EvidenceBundle } from '../evidence/types.ts';
import type { ThreadReplyInput } from '../prompts/thread-reply.ts';

/**
 * Reconstructs the inline review thread context around `commentId` from the
 * collected PR comments in an EvidenceBundle.
 */
export function buildThreadContextFromBundle(
  bundle: EvidenceBundle,
  commentId: number,
  question: string,
): ThreadReplyInput {
  const reviewComments = bundle.comments.filter((c) => c.kind === 'review_comment');
  const byId = new Map(reviewComments.map((c) => [Number(c.id), c]));
  const target = byId.get(commentId);

  // Walk up inReplyToId to find root comment of this review thread
  let rootId = commentId;
  const visited = new Set<number>([commentId]);
  let cursor = target;
  while (cursor?.inReplyToId && !visited.has(cursor.inReplyToId)) {
    visited.add(cursor.inReplyToId);
    const parent = byId.get(cursor.inReplyToId);
    if (!parent) {
      rootId = cursor.inReplyToId;
      break;
    }
    rootId = Number(parent.id);
    cursor = parent;
  }

  const rootComment = byId.get(rootId) ?? target;
  const threadHistory = reviewComments
    .filter((c) => {
      const id = Number(c.id);
      if (id === commentId || id === rootId) return false;
      return c.inReplyToId === rootId || c.inReplyToId === commentId;
    })
    .map((c) => ({ author: c.author, body: c.body }));

  return {
    repo: bundle.pr.repo,
    prNumber: bundle.pr.prNumber,
    path: target?.path ?? rootComment?.path,
    line: target?.line ?? rootComment?.line,
    originalComment: rootComment?.body ?? '(original review comment not found in bundle)',
    threadHistory,
    userFollowUp: question || target?.body || 'Please clarify this review thread.',
  };
}

/**
 * Formats an inline review thread reply body, optionally embedding a hidden
 * `trigger_comment` marker so watchers never post duplicate replies.
 */
export function formatThreadReplyBody(
  reply: {
    reply: string;
    resolved: boolean;
    references: string[];
  },
  options: { triggerCommentId?: number } = {},
): string {
  const lines = [reply.reply.trim()];
  if (reply.references.length > 0) {
    lines.push('', `**References:** ${reply.references.map((r) => `\`${r}\``).join(', ')}`);
  }
  lines.push(
    '',
    `<sub>Status: ${reply.resolved ? '✅ Resolved' : '🔎 Open'} · Generated by \`civireview reply\`</sub>`,
  );
  if (options.triggerCommentId !== undefined) {
    lines.push(`<!-- civireview:reply trigger_comment=${options.triggerCommentId} -->`);
  }
  return lines.join('\n');
}

const REPLY_MARKER_RE = /<!--\s*civireview:reply\b[^>]*\btrigger_comment=(\d+)\b[^>]*-->/gi;

/**
 * Returns true if any comment body already contains a `civireview:reply` marker
 * for the given `triggerCommentId`.
 */
export function hasExistingThreadReplyMarker(
  comments: Array<{ body?: string | null }>,
  triggerCommentId: number,
): boolean {
  for (const c of comments) {
    const body = c.body ?? '';
    if (!body.includes('civireview:reply')) continue;
    REPLY_MARKER_RE.lastIndex = 0;
    let match = REPLY_MARKER_RE.exec(body);
    while (match) {
      if (Number(match[1]) === triggerCommentId) {
        return true;
      }
      match = REPLY_MARKER_RE.exec(body);
    }
  }
  return false;
}
